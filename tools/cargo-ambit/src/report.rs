//! The attack-surface report: for every program the workspace builds, what ends up in it and
//! what runs while building it, with what each crate may do (from `cackle.toml`).
//!
//! `cargo ambit report` writes it to `attack-surface.md`; `cargo ambit check` fails when that
//! file is out of date. The file is human-owned, so a change to what ships (a new crate, a new
//! version, a new permission, a kernel feature) shows up as a change to it in the commit,
//! for the reviewer to approve.
//!
//! - A program is a workspace member with a `bin` target, outside `apps/` and `tools/`.
//! - It's resolved for `x86_64-unknown-linux-gnu` (so the report doesn't depend on the machine
//!   it's made on), or for the target in `[package.metadata.ambit] target`.
//! - Lines are non-blank lines of Rust in the crate's package, without its tests, benches and
//!   examples. Workspace crates aren't counted: they're reviewed in this repository, and their
//!   counts would change with every edit.

use std::collections::{BTreeMap, BTreeSet};
use std::fmt::Write as _;
use std::path::{Path, PathBuf};

use serde_json::Value;

use crate::apps::{self, Metadata};

pub const FILE: &str = "attack-surface.md";
const DEFAULT_TARGET: &str = "x86_64-unknown-linux-gnu";
/// Directories in a package that don't end up in a program.
const SKIPPED_DIRS: &[&str] = &["tests", "benches", "examples", "target"];

/// The report as it should be now.
pub fn generate() -> Result<String, String> {
    let meta = Metadata::load_no_deps()?;
    let programs = programs(&meta);
    let mut by_target: BTreeMap<&str, Metadata> = BTreeMap::new();
    by_target.insert(DEFAULT_TARGET, Metadata::load_for(DEFAULT_TARGET)?);
    // cackle analyses the build for this machine, which is Linux in CI: crates only another
    // target uses aren't checked.
    let cackle = Grants {
        table: apps::cackle_packages(&meta)?,
        checked: by_target[DEFAULT_TARGET]
            .nodes()?
            .keys()
            .map(|id| id.to_string())
            .collect(),
    };
    for program in &programs {
        if !by_target.contains_key(program.target.as_str()) {
            by_target.insert(&program.target, Metadata::load_for(&program.target)?);
        }
    }

    let mut out = String::from(
        "# Attack surface\n\n\
         What each program built here contains, and what runs while it's built. Generated by \
         `cargo ambit report`; `cargo ambit check` fails when it's out of date, so a change to \
         any of this shows up here, in the commit that makes it.\n\n\
         - **ships**: compiled into the program. **build time**: build scripts, proc macros and \
         what they use; they run on the build machine, not in the program.\n\
         - **lines**: non-blank lines of Rust, without tests and examples. Code from this \
         workspace isn't counted: it's reviewed here. A crate's whole package is counted, \
         including code for other platforms that isn't compiled in (`libc` and `linux-raw-sys` \
         hold bindings for every platform), so read the numbers as a size class, and their \
         changes as the signal.\n\
         - **may use**: what `cackle.toml` lets the crate's own code do (`unsafe`, or APIs such \
         as `net` and `fs`). Empty means nothing beyond computing.\n",
    );
    for program in &programs {
        let meta = &by_target[program.target.as_str()];
        write_program(&mut out, meta, &cackle, program)?;
    }
    Ok(out)
}

struct Grants {
    table: toml::Table,
    /// Package ids cackle analyses.
    checked: BTreeSet<String>,
}

struct Program {
    id: String,
    package: String,
    bins: Vec<String>,
    target: String,
}

/// The crates (name, version) cargo builds for this program alone, as `cargo build -p` would:
/// features only from what the program uses, not from the rest of the workspace or its tests.
fn built_for(program: &Program) -> Result<BTreeSet<(String, String)>, String> {
    let output = std::process::Command::new("cargo")
        .args(["tree", "--locked", "-e", "normal,build", "--prefix", "none"])
        .args([
            "-f",
            "{p}",
            "--target",
            &program.target,
            "-p",
            &program.package,
        ])
        .output()
        .map_err(|e| format!("cargo tree: {e}"))?;
    if !output.status.success() {
        return Err(format!(
            "cargo tree -p {} failed:\n{}",
            program.package,
            String::from_utf8_lossy(&output.stderr)
        ));
    }
    Ok(String::from_utf8_lossy(&output.stdout)
        .lines()
        .filter_map(|line| {
            let mut words = line.split_whitespace();
            let name = words.next()?;
            let version = words.next()?.strip_prefix('v')?;
            Some((name.to_string(), version.to_string()))
        })
        .collect())
}

fn programs(meta: &Metadata) -> Vec<Program> {
    let root = meta.workspace_root();
    let excluded = [root.join("apps"), root.join("tools")];
    let packages = meta.packages();
    let mut programs: Vec<Program> = meta
        .members()
        .into_iter()
        .filter_map(|id| {
            let p = packages.get(id)?;
            let manifest = Path::new(p["manifest_path"].as_str()?);
            if excluded.iter().any(|dir| manifest.starts_with(dir)) {
                return None;
            }
            let bins: Vec<String> = targets(p)
                .filter(|t| kinds(t).any(|k| k == "bin"))
                .filter_map(|t| Some(t["name"].as_str()?.to_string()))
                .collect();
            (!bins.is_empty()).then(|| Program {
                id: id.to_string(),
                package: p["name"].as_str().unwrap_or(id).to_string(),
                bins,
                target: p["metadata"]["ambit"]["target"]
                    .as_str()
                    .unwrap_or(DEFAULT_TARGET)
                    .to_string(),
            })
        })
        .collect();
    programs.sort_by(|a, b| a.package.cmp(&b.package));
    programs
}

fn targets(package: &Value) -> impl Iterator<Item = &Value> {
    package["targets"].as_array().into_iter().flatten()
}

fn kinds(target: &Value) -> impl Iterator<Item = &str> {
    target["kind"]
        .as_array()
        .into_iter()
        .flatten()
        .filter_map(Value::as_str)
}

fn is_proc_macro(package: &Value) -> bool {
    targets(package).any(|t| kinds(t).any(|k| k == "proc-macro"))
}

fn has_build_script(package: &Value) -> bool {
    targets(package).any(|t| kinds(t).any(|k| k == "custom-build"))
}

fn write_program(
    out: &mut String,
    meta: &Metadata,
    cackle: &Grants,
    program: &Program,
) -> Result<(), String> {
    let packages = meta.packages();
    let members = meta.members();
    let nodes = meta.nodes()?;
    let edges = |id: &str, keep: &dyn Fn(Option<&str>) -> bool| -> Vec<String> {
        nodes
            .get(id)
            .and_then(|n| n["deps"].as_array())
            .into_iter()
            .flatten()
            .filter(|d| {
                d["dep_kinds"]
                    .as_array()
                    .into_iter()
                    .flatten()
                    .any(|k| keep(k["kind"].as_str()))
            })
            .filter_map(|d| Some(d["pkg"].as_str()?.to_string()))
            .collect()
    };

    // Ships: normal edges, not into proc macros (they run in the compiler).
    let mut ships = BTreeSet::new();
    let mut todo = vec![program.id.clone()];
    while let Some(id) = todo.pop() {
        for dep in edges(&id, &|kind| kind.is_none()) {
            if !is_proc_macro(packages[dep.as_str()]) && ships.insert(dep.clone()) {
                todo.push(dep);
            }
        }
    }
    // Build time: build dependencies and proc macros of anything above, and what they use.
    let mut build = BTreeSet::new();
    let mut todo: Vec<String> = ships
        .iter()
        .cloned()
        .chain([program.id.clone()])
        .flat_map(|id| {
            let mut deps = edges(&id, &|kind| kind == Some("build"));
            deps.extend(
                edges(&id, &|kind| kind.is_none())
                    .into_iter()
                    .filter(|d| is_proc_macro(packages[d.as_str()])),
            );
            deps
        })
        .collect();
    while let Some(id) = todo.pop() {
        if ships.contains(&id) || !build.insert(id.clone()) {
            continue;
        }
        todo.extend(edges(&id, &|kind| kind.is_none() || kind == Some("build")));
    }

    // The graph above has every feature any workspace member turns on, tests' included. What
    // this program's build actually uses is narrower: keep only the crates cargo builds for it.
    let built = built_for(program)?;
    let in_build = |id: &String| {
        let p = packages[id.as_str()];
        built.contains(&(
            p["name"].as_str().unwrap_or("").to_string(),
            p["version"].as_str().unwrap_or("").to_string(),
        ))
    };
    ships.retain(&in_build);
    build.retain(&in_build);

    let bins = program.bins.join("`, `");
    if program.bins == [program.package.clone()] {
        writeln!(out, "\n## `{bins}`, for {}\n", program.target).ok();
    } else {
        writeln!(
            out,
            "\n## `{bins}` ({}, for {})\n",
            program.package, program.target
        )
        .ok();
    }

    let rows = Row::all(&ships, &packages, &members, cackle);
    let outside: Vec<&Row> = rows.iter().filter(|r| r.lines.is_some()).collect();
    let lines: u64 = outside.iter().filter_map(|r| r.lines).sum();
    writeln!(
        out,
        "{} crates ship: {} from this workspace, {} from outside it with {} lines of Rust. \
         {} more run at build time.\n",
        rows.len(),
        rows.len() - outside.len(),
        outside.len(),
        thousands(lines),
        build.len()
    )
    .ok();
    if let Some(hermit) = packages
        .iter()
        .find(|(id, p)| ships.contains(**id) && p["name"] == "hermit")
    {
        let features: Vec<&str> = nodes[hermit.0]["features"]
            .as_array()
            .into_iter()
            .flatten()
            .filter_map(Value::as_str)
            .filter(|f| *f != "default")
            .collect();
        writeln!(
            out,
            "Hermit kernel features (each adds kernel code to the image): {}. The kernel itself \
             is built by `hermit`'s build script and isn't counted here.\n",
            features.join(", ")
        )
        .ok();
    }

    writeln!(
        out,
        "| ships | version | from | lines | may use | build script may use |\n\
         |---|---|---|--:|---|---|"
    )
    .ok();
    for row in &rows {
        writeln!(
            out,
            "| {} | {} | {} | {} | {} | {} |",
            row.name,
            row.version,
            row.from,
            row.lines.map_or("-".into(), thousands),
            row.may_use.join(", "),
            row.build.as_deref().unwrap_or("-"),
        )
        .ok();
    }

    if !build.is_empty() {
        writeln!(
            out,
            "\n| build time | version | from | lines | may use |\n|---|---|---|--:|---|"
        )
        .ok();
        for row in &Row::all(&build, &packages, &members, cackle) {
            let mut may_use = row.may_use.clone();
            may_use.extend(
                row.build
                    .iter()
                    .filter(|b| *b != "nothing" && !row.may_use.contains(b))
                    .cloned(),
            );
            writeln!(
                out,
                "| {} | {} | {} | {} | {} |",
                row.name,
                row.version,
                row.from,
                row.lines.map_or("-".into(), thousands),
                may_use.join(", "),
            )
            .ok();
        }
    }
    Ok(())
}

struct Row {
    name: String,
    version: String,
    from: String,
    /// `None` for workspace crates.
    lines: Option<u64>,
    may_use: Vec<String>,
    /// `None` without a build script.
    build: Option<String>,
}

impl Row {
    /// Workspace crates first, then by name and version.
    fn all(
        ids: &BTreeSet<String>,
        packages: &BTreeMap<&str, &Value>,
        members: &BTreeSet<&str>,
        cackle: &Grants,
    ) -> Vec<Self> {
        let mut rows: Vec<Self> = ids
            .iter()
            .map(|id| {
                Self::new(
                    id,
                    packages[id.as_str()],
                    members.contains(id.as_str()),
                    cackle,
                )
            })
            .collect();
        rows.sort_by(|a, b| {
            (a.lines.is_some(), &a.name, &a.version).cmp(&(b.lines.is_some(), &b.name, &b.version))
        });
        rows
    }

    fn new(id: &str, package: &Value, member: bool, cackle: &Grants) -> Self {
        let name = package["name"].as_str().unwrap_or("?").to_string();
        let checked = cackle.checked.contains(id);
        let entry = cackle.table.get(&name);
        let list = |key: &str| -> Vec<String> {
            let mut value = entry;
            for part in key.split('.') {
                value = value.and_then(|v| v.get(part));
            }
            value
                .and_then(toml::Value::as_array)
                .into_iter()
                .flatten()
                .filter_map(toml::Value::as_str)
                .map(str::to_string)
                .collect()
        };
        let mut may_use = Vec::new();
        if entry.and_then(|e| e.get("allow_unsafe")) == Some(&toml::Value::Boolean(true)) {
            may_use.push("unsafe".to_string());
        }
        if entry.and_then(|e| e.get("allow_proc_macro")) == Some(&toml::Value::Boolean(true)) {
            may_use.push("proc macro".to_string());
        }
        may_use.extend(list("allow_apis"));
        if !checked {
            may_use = vec!["not checked by cackle".to_string()];
        }
        let build = has_build_script(package).then(|| {
            let apis = list("build.allow_apis");
            if !checked {
                "not checked by cackle".to_string()
            } else if apis.is_empty() {
                "nothing".to_string()
            } else {
                apis.join(", ")
            }
        });
        let manifest = PathBuf::from(package["manifest_path"].as_str().unwrap_or("."));
        Self {
            version: package["version"].as_str().unwrap_or("?").to_string(),
            from: if member {
                "workspace".into()
            } else {
                source(package["source"].as_str().unwrap_or(""))
            },
            lines: (!member).then(|| manifest.parent().map_or(0, rust_lines)),
            may_use,
            build,
            name,
        }
    }
}

/// `crates.io`, or `git github.com/eelcoh/ambit` without the revision.
fn source(source: &str) -> String {
    if source.starts_with("registry+https://github.com/rust-lang/crates.io-index") {
        return "crates.io".into();
    }
    match source.strip_prefix("git+") {
        Some(url) => {
            let url = url.split(['?', '#']).next().unwrap_or(url);
            let url = url.strip_prefix("https://").unwrap_or(url);
            format!("git {}", url.trim_end_matches(".git"))
        }
        None if source.is_empty() => "path".into(),
        None => source.into(),
    }
}

fn rust_lines(dir: &Path) -> u64 {
    let Ok(entries) = std::fs::read_dir(dir) else {
        return 0;
    };
    let mut entries: Vec<PathBuf> = entries.filter_map(|e| Some(e.ok()?.path())).collect();
    entries.sort();
    entries
        .iter()
        .map(|path| {
            let name = path.file_name().and_then(|n| n.to_str()).unwrap_or("");
            if path.is_dir() {
                if name.starts_with('.') || SKIPPED_DIRS.contains(&name) {
                    0
                } else {
                    rust_lines(path)
                }
            } else if name.ends_with(".rs") {
                std::fs::read_to_string(path).map_or(0, |text| {
                    text.lines().filter(|l| !l.trim().is_empty()).count() as u64
                })
            } else {
                0
            }
        })
        .sum()
}

/// `12345` as `12,345`.
fn thousands(n: u64) -> String {
    let digits = n.to_string();
    let mut out = String::new();
    for (i, c) in digits.chars().enumerate() {
        if i > 0 && (digits.len() - i).is_multiple_of(3) {
            out.push(',');
        }
        out.push(c);
    }
    out
}

/// Writes the report to the workspace root.
pub fn write() -> Result<PathBuf, String> {
    let path = Metadata::load_no_deps()?.workspace_root().join(FILE);
    std::fs::write(&path, generate()?).map_err(|e| format!("{}: {e}", path.display()))?;
    Ok(path)
}

/// Whether the report in the workspace is up to date.
pub fn check() -> Result<(), String> {
    let path = Metadata::load_no_deps()?.workspace_root().join(FILE);
    let current = std::fs::read_to_string(&path).unwrap_or_default();
    if current == generate()? {
        println!("attack surface: {FILE} is up to date");
        Ok(())
    } else if current.is_empty() {
        Err(format!(
            "no {FILE}: run `cargo ambit report`, review it and commit it"
        ))
    } else {
        Err(format!(
            "{FILE} is out of date: what ships has changed. Run `cargo ambit report` and \
             commit it, so the change shows in the commit"
        ))
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn numbers_and_sources_read_well() {
        assert_eq!(thousands(0), "0");
        assert_eq!(thousands(999), "999");
        assert_eq!(thousands(1000), "1,000");
        assert_eq!(thousands(1234567), "1,234,567");
        assert_eq!(
            source("registry+https://github.com/rust-lang/crates.io-index"),
            "crates.io"
        );
        assert_eq!(
            source("git+https://github.com/eelcoh/ambit?rev=14a65c8#14a65c89"),
            "git github.com/eelcoh/ambit"
        );
        assert_eq!(
            source("git+https://github.com/hermit-os/hermit-rs.git?tag=hermit-0.13.2#abc"),
            "git github.com/hermit-os/hermit-rs"
        );
    }
}
